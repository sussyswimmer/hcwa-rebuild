"""Encode the Blender wall maps (prototype/blender/walls.py) for the live world (PLAN 9, "M5 walls").

    python3 scripts/encode-walls.py [blender_out=blender/out]

Reads <name>-albedo.png and <name>-normal.png (1024 px, seamless) for every material and writes, under
public/textures/:
  <name>-<size>.webp     albedo (sRGB), 512 px for Tier 1 and 1024 px for Tier 2
  <name>-n-<size>.webp   tangent-space normal (OpenGL, +Y up); the shaders read only R and G
and src/world/walls-data.js: each map's mean albedo in linear light (the shaders divide by it, so the house
tokens keep setting the hue and only the relief comes from the map) and the byte sizes (the budget test
reads the files themselves). Roughness is not shipped: the world's analytic light has no specular term.
The normal map is low-passed a little before encoding (0.8 px at 1024): the 2 mm grit it drops is below a
pixel on any screen at these distances and was half of every file.
"""
import io
import json
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, "blender", "out")
OUT = os.path.join(ROOT, "public", "textures")
DATA = os.path.join(ROOT, "src", "world", "walls-data.js")
NAMES = ["plaster", "limewash", "dado", "paint", "concrete"]
SIZES = {512: {"blur": 0.4, "qa": 82, "qn": 72}, 1024: {"blur": 0.8, "qa": 80, "qn": 70}}
# Bytes the home page may load per tier (every material is on it): the budget test holds the same numbers.
BUDGET = {512: 300 * 1024, 1024: 800 * 1024}


def lin(a):
    return np.where(a <= 0.04045, a / 12.92, ((a + 0.055) / 1.055) ** 2.4)


def webp(im, q):
    b = io.BytesIO()
    im.save(b, "WEBP", quality=q, method=6)
    return b.getvalue()


def main():
    os.makedirs(OUT, exist_ok=True)
    data = {"names": NAMES, "sizes": sorted(SIZES), "mean": {}, "bytes": {}}
    for s in SIZES:
        data["bytes"][s] = {}
    for n in NAMES:
        a0 = Image.open(os.path.join(SRC, f"{n}-albedo.png")).convert("RGB")
        n0 = Image.open(os.path.join(SRC, f"{n}-normal.png")).convert("RGB")
        if a0.size != n0.size or a0.size[0] != a0.size[1]:
            raise SystemExit(f"{n}: maps must be square and the same size")
        for s, o in SIZES.items():
            a = a0.resize((s, s), Image.LANCZOS) if a0.size[0] != s else a0
            nm = n0.resize((s, s), Image.LANCZOS) if n0.size[0] != s else n0
            nm = nm.filter(ImageFilter.GaussianBlur(o["blur"]))
            ab, nb = webp(a, o["qa"]), webp(nm, o["qn"])
            with open(os.path.join(OUT, f"{n}-{s}.webp"), "wb") as f:
                f.write(ab)
            with open(os.path.join(OUT, f"{n}-n-{s}.webp"), "wb") as f:
                f.write(nb)
            data["bytes"][s][n] = [len(ab), len(nb)]
            if s == 512:
                # The mean the shader divides by: of the map it will sample (the decoded 512 px file; the 1024 px
                # one differs by well under 1%).
                d = np.asarray(Image.open(io.BytesIO(ab)).convert("RGB")).astype(np.float64) / 255
                data["mean"][n] = [round(float(v), 4) for v in lin(d).mean((0, 1))]
        print(f"{n}: mean {data['mean'][n]} " + " ".join(f"{s}px {sum(data['bytes'][s][n]) // 1024} KB" for s in SIZES))
    for s in SIZES:
        total = sum(sum(v) for v in data["bytes"][s].values())
        print(f"total {s}px: {total / 1024:.1f} KB (budget {BUDGET[s] // 1024} KB)")
        if total > BUDGET[s]:
            raise SystemExit(f"over budget at {s}px")
    with open(DATA, "w") as f:
        f.write("// Generated by scripts/encode-walls.py from the Blender bake (blender/walls.py). Do not edit.\n")
        f.write("// mean: each albedo's mean in linear light; bytes: [albedo, normal] per size, as encoded.\n")
        f.write(f"export const WALL_DATA = {json.dumps(data, indent=1)};\n")


main()
