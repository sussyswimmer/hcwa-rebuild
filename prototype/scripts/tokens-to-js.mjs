// tokens.css → src/motion/tokens.js and src/world/tokens.js (05-DESIGN D1, D5.1).
// Runs before dev and build; `node scripts/tokens-to-js.mjs --check` exits 1 on drift.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const paths = {
  css: resolve(root, "src/styles/tokens.css"),
  motion: resolve(root, "src/motion/tokens.js"),
  world: resolve(root, "src/world/tokens.js"),
};

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const HEAD = "// GENERATED by scripts/tokens-to-js.mjs from src/styles/tokens.css. Do not edit.\n";
const obj = (o, indent = "  ") => `{\n${Object.entries(o).map(([k, v]) => `${indent}${/^[a-z]\w*$/i.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n}`;

export function parse(css) {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const colors = {}, ease = {}, bezier = {}, dur = {};
  for (const [, name, hex] of body.matchAll(/--color-([\w-]+):\s*(#[0-9a-f]{6})\b/gi)) colors[name] = hex.toUpperCase();
  for (const [, name, args] of body.matchAll(/--ease-([\w-]+):\s*cubic-bezier\(([^)]+)\)/g)) {
    const nums = args.split(",").map((n) => Number(n.trim()));
    ease[camel(name)] = nums.join(",");
    bezier[camel(name)] = nums;
  }
  for (const [, name, ms] of body.matchAll(/--d-([\w-]+):\s*(\d+)ms/g)) dur[camel(name)] = Number(ms);
  const stagger = Number(body.match(/--stagger:\s*(\d+)ms/)?.[1] ?? 0);
  if (!Object.keys(colors).length || !ease.out || !dur.ui) throw new Error("tokens.css: colors, --ease-out or --d-ui not found");
  return { colors, ease, bezier, dur, stagger };
}

export function generate(css) {
  const t = parse(css);
  const shared = `// CustomEase strings ("0.23,1,0.32,1") and the same curves as numbers.
export const ease = ${obj(t.ease)};
export const bezier = ${obj(t.bezier)};
// Milliseconds.
export const dur = ${obj(t.dur)};
export const stagger = ${t.stagger};
`;
  const world = Object.fromEntries(Object.entries(t.colors).filter(([k]) => k.startsWith("world-")).map(([k, v]) => [camel(k.slice(6)), v]));
  return {
    motion: HEAD + shared,
    world: `${HEAD}// Every --color-* token by its CSS name, and the world-* shader targets in camelCase.
export const color = ${obj(t.colors)};
export const world = ${obj(world)};
${shared}`,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generate(readFileSync(paths.css, "utf8"));
  const check = process.argv.includes("--check");
  let drift = false;
  for (const key of ["motion", "world"]) {
    let current = null;
    try { current = readFileSync(paths[key], "utf8"); } catch { /* first run */ }
    if (current === out[key]) continue;
    if (check) { console.error(`${paths[key]} is out of date: run npm run tokens`); drift = true; continue; }
    mkdirSync(dirname(paths[key]), { recursive: true });
    writeFileSync(paths[key], out[key]);
    console.log(`tokens → ${paths[key]}`);
  }
  if (drift) process.exit(1);
}
